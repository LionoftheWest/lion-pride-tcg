/**
 * Write the database STRUCTURE snapshot to db/schema/ from the catalog of the LOCAL copy.
 *   LOCALDB=1 node --import ./scripts/localdb-preload.mjs scripts/gen-schema-snapshot.mjs     (from card-studio/)
 *   node scripts/gen-schema-snapshot.mjs --cron-from-live     only db/schema/cron-jobs.sql, read-only from LIVE
 *
 * Why the local copy: a migration is rehearsed there first (rehearse-sql.mjs), so the snapshot of a PR shows
 * the structure AFTER its migration, before it goes live. check-schema-drift.mjs compares it again.
 *
 * It writes (LF, sorted, deterministic; a second run with no database change gives no diff):
 *   db/schema/tables/<name>.sql       columns, types, defaults, constraints, indexes, RLS, policies, grants, triggers
 *   db/schema/functions/<name>.sql    the full pg_get_functiondef text (CR removed), its md5, owner and grants
 *   db/schema/functions.md5           one line per function: the md5 for a migration guard
 *   db/schema/types.sql, sequences.sql, extensions.sql
 *   db/schema/cron-jobs.sql           the pg_cron jobs. The local copy has NO cron jobs (the dump does not carry
 *                                     them), so this file comes from live (--cron-from-live). A local run with
 *                                     no jobs leaves it as it is.
 * It reads only the catalog: no row, no settings or balance value, no sequence value. It refuses to write a
 * file that looks like it holds a secret.
 */
import dotenv from 'dotenv'; dotenv.config({ override: true });
import { mkdirSync, readdirSync, unlinkSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join, dirname } from 'node:path';
import { makeQ, readCatalog, renderSnapshot, renderCron, findSecrets, CRON_FILE, SNAPSHOT_DIR_URL } from './schema-snapshot-lib.mjs';

const OUT = fileURLToPath(SNAPSHOT_DIR_URL);
const CRON_LIVE = process.argv.includes('--cron-from-live');
if (!CRON_LIVE && process.env.LOCALDB !== '1') {
  console.error('gen-schema-snapshot: run it on the LOCAL copy: LOCALDB=1 node --import ./scripts/localdb-preload.mjs scripts/gen-schema-snapshot.mjs');
  process.exit(2);
}
if (CRON_LIVE && process.env.LOCALDB === '1') { console.error('gen-schema-snapshot: --cron-from-live reads live: run it without LOCALDB=1'); process.exit(2); }
const q = makeQ();

const writeChecked = (files) => {
  const secrets = findSecrets(files);
  if (secrets.length) { console.error(`gen-schema-snapshot: REFUSED, a possible secret in: ${secrets.join(', ')}`); process.exit(1); }
  for (const [p, text] of files) { mkdirSync(dirname(join(OUT, p)), { recursive: true }); writeFileSync(join(OUT, p), text); }
};

if (CRON_LIVE) {
  // Read-only: the catalog queries are single SELECTs (assertSelect). Only the cron part is used.
  const hasCron = (await q(`select to_regclass('cron.job') is not null as yes`))[0]?.yes;
  const cron = hasCron ? await q(`select jobname as name, schedule, command, active from cron.job`) : [];
  writeChecked(new Map([[CRON_FILE, renderCron({ cron })]]));
  console.log(`wrote db/schema/${CRON_FILE}: ${cron.length} cron jobs (from live, read-only)`);
  process.exit(0);
}

const cat = await readCatalog(q);
const files = renderSnapshot(cat);
// cron-jobs.sql comes from live only (--cron-from-live): a local copy has no real jobs, and a test or a migration
// may schedule one there.
// A removed table or function leaves no old file.
for (const d of ['tables', 'functions']) if (existsSync(join(OUT, d))) for (const f of readdirSync(join(OUT, d))) if (!files.has(`${d}/${f}`)) unlinkSync(join(OUT, d, f));
writeChecked(files);
writeFileSync(join(OUT, 'README.md'), `# The database structure snapshot

> Generated by \`card-studio/scripts/gen-schema-snapshot.mjs\`. Do not edit the files in this folder by hand.

This folder is the STRUCTURE of the live database (Supabase project of Lion Pride TCG): one file per table and per
function, the types, the sequences, the extensions and the pg_cron jobs. It holds no rows and no game values (the
\`settings\` and \`balance\` values are data: \`docs/data/balance.md\` shows the balance values).

- \`functions/<name>.sql\`: the full function text and its md5. A migration guard uses the same formula:
  \`md5(replace(pg_get_functiondef('<function>'::regprocedure), chr(13), ''))\`. \`functions.md5\` lists all of them.
- \`tables/<name>.sql\`: columns, constraints, indexes, row level security, policies, grants, triggers.

## How a PR uses it (from \`card-studio/\`)

1. Rehearse the migration on the local copy: \`node scripts/rehearse-sql.mjs <file.sql>\`.
2. Generate the snapshot again: \`LOCALDB=1 node --import ./scripts/localdb-preload.mjs scripts/gen-schema-snapshot.mjs\`.
3. Make the superseded list again: \`LOCALDB=1 node --import ./scripts/localdb-preload.mjs scripts/find-superseded.mjs\`.
4. Commit \`db/schema/\` and \`tcg-bot/supabase/SUPERSEDED.md\` with the migration. The diff shows the real change.
5. After the migration is live: \`node scripts/check-schema-drift.mjs --live\` must show 0 differences.

\`test-schema-snapshot.mjs\` (in \`test-all-local.mjs\`) fails when the local copy and this folder differ.
After each deploy, \`node scripts/check-schema-drift.mjs --live\` (read-only) compares this folder with LIVE.
It finds a hand change on live, or an old migration that was run again. \`tcg-bot/supabase/SUPERSEDED.md\` lists
the old files that would put an old version back (\`apply-sql.mjs\` refuses them).

The local copy has no pg_cron jobs, so \`cron-jobs.sql\` comes from live: \`node scripts/gen-schema-snapshot.mjs --cron-from-live\`.
`);
const counts = { tables: cat.rels.length, functions: cat.fns.length, enums: cat.enums.length, sequences: cat.seqs.length, extensions: cat.exts.length, cron: cat.cron.length };
console.log(`wrote db/schema/: ${Object.entries(counts).map(([k, v]) => `${v} ${k}`).join(', ')}${cat.cron.length ? '' : ` (no cron jobs in this database: ${CRON_FILE} left as it is)`}`);
