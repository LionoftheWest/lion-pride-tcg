/**
 * The database STRUCTURE snapshot (db/schema/): shared by gen-schema-snapshot.mjs (writes it),
 * check-schema-drift.mjs (compares it with a database) and test-schema-snapshot.mjs (test-all-local).
 *
 * It reads ONLY the catalog (pg_class, pg_attribute, pg_constraint, pg_index, pg_policy, pg_trigger,
 * pg_proc, pg_type, pg_sequence, pg_extension, cron.job). It never reads a table row, a row count, a
 * settings or balance value or a sequence value. Every query is a single SELECT (assertSelect below),
 * so the live check is read-only.
 *
 * buildSnapshot(q) returns a Map of "relative path" -> file text (LF only, sorted, deterministic).
 * Each file has sections that start with a line "-- @<kind>"; the drift check names the kind that differs.
 */

export const SNAPSHOT_DIR_URL = new URL('../../db/schema/', import.meta.url);
export const HEADER = '-- Generated by card-studio/scripts/gen-schema-snapshot.mjs from the database catalog. Do not edit by hand.';
// The guard formula of the migrations: md5 of the function definition with CR removed.
export const MD5_FORMULA = (ident) => `md5(replace(pg_get_functiondef('${ident}'::regprocedure), chr(13), ''))`;

export const assertSelect = (sql) => {
  const s = sql.replace(/^\s+/, '');
  if (!/^(select|with)\b/i.test(s) || /;\s*\S/.test(s.replace(/;\s*$/, ''))) throw new Error(`schema snapshot: only a single SELECT is allowed:\n${sql.slice(0, 200)}`);
  return sql;
};

/** The SQL endpoint of the Management API (LOCALDB=1 + localdb-preload.mjs send it to the local copy). SELECTs only. */
export const makeQ = () => {
  const ref = (process.env.SUPABASE_URL || '').match(/https:\/\/([a-z0-9]+)/)?.[1];
  if (!ref || !process.env.SUPABASE_ACCESS_TOKEN) throw new Error('SUPABASE_URL and SUPABASE_ACCESS_TOKEN are needed in card-studio/.env');
  return async (query) => {
    assertSelect(query);
    const r = await fetch(`https://api.supabase.com/v1/projects/${ref}/database/query`, { method: 'POST', headers: { Authorization: `Bearer ${process.env.SUPABASE_ACCESS_TOKEN}`, 'Content-Type': 'application/json' }, body: JSON.stringify({ query }) });
    const j = await r.json();
    if (!Array.isArray(j)) throw new Error(`query failed: ${JSON.stringify(j).slice(0, 300)}`);
    return j;
  };
};

/** Read the snapshot files in the repo (db/schema/) as a Map path -> text (CR removed: a Windows checkout may add CR). */
export async function readSnapshotDir() {
  const { readdirSync, readFileSync, existsSync } = await import('node:fs');
  const { fileURLToPath } = await import('node:url');
  const root = fileURLToPath(SNAPSHOT_DIR_URL);
  const files = new Map();
  if (!existsSync(root)) return files;
  const walk = (rel) => {
    for (const e of readdirSync(root + rel, { withFileTypes: true })) {
      const p = rel + e.name;
      if (e.isDirectory()) walk(p + '/');
      else if (e.name !== 'README.md') files.set(p, readFileSync(root + p, 'utf8').replace(/\r/g, ''));
    }
  };
  walk('');
  return files;
}

/**
 * Flatten nested AND groups in a deparsed expression: "((a) AND (b)) AND (c)" -> "(a) AND (b) AND (c)".
 * Why: a dump and restore re-parses each CHECK, and the parser makes one flat AND list, so the clone prints
 * fewer parentheses than live for the same rule (seen on gift_claims_amount_check, 2026-10-07). AND is
 * associative, so the flat text has the same meaning. Quoted literals are kept as they are.
 */
export function flattenAnd(src) {
  let i = 0;
  const parse = () => { // returns a list of parts: string | { kids: parts }
    const parts = []; let buf = '';
    while (i < src.length) {
      const ch = src[i];
      if (ch === "'" || ch === '"') { let j = i + 1; while (j < src.length && !(src[j] === ch && src[j + 1] !== ch)) j += src[j] === ch ? 2 : 1; buf += src.slice(i, j + 1); i = j + 1; continue; }
      if (ch === '(') { if (buf) parts.push(buf); buf = ''; i += 1; parts.push({ kids: parse() }); continue; }
      if (ch === ')') { i += 1; break; }
      buf += ch; i += 1;
    }
    if (buf) parts.push(buf);
    return parts;
  };
  // Split a part list at top-level " AND " into items (each item a part list).
  const andItems = (parts) => {
    const items = [[]];
    for (const p of parts) {
      if (typeof p !== 'string') { items[items.length - 1].push(p); continue; }
      const segs = p.split(' AND ');
      segs.forEach((s, k) => { if (k) items.push([]); if (s) items[items.length - 1].push(s); });
    }
    return items;
  };
  const isGroup = (item) => item.length === 1 && typeof item[0] !== 'string';
  const norm = (parts) => {
    const kids = parts.map((p) => (typeof p === 'string' ? p : { kids: norm(p.kids) }));
    const items = andItems(kids);
    // Only a pure AND level (no top-level OR) is flattened, so the operator precedence cannot change.
    const hasOr = (ps) => ps.some((p) => typeof p === 'string' && / OR /.test(p));
    if (items.length < 2 || hasOr(kids)) return kids;
    const out = [];
    for (const it of items) {
      if (isGroup(it) && !hasOr(it[0].kids)) { const inner = andItems(it[0].kids); if (inner.length >= 2 && inner.every((x) => x.length)) { out.push(...inner); continue; } }
      out.push(it);
    }
    return out.flatMap((it, k) => (k ? [' AND ', ...it] : it));
  };
  const ser = (parts) => parts.map((p) => (typeof p === 'string' ? p : `(${ser(p.kids)})`)).join('');
  const tree = parse();
  return i < src.length ? src : ser(norm(tree)).replace(/ AND  AND /g, ' AND ');
}

const cmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const by = (f) => (a, b) => cmp(f(a), f(b));
const lf = (s) => String(s ?? '').replace(/\r/g, '');
const qi = (s) => (/^[a-z_][a-z0-9_]*$/.test(s) ? s : `"${s.replace(/"/g, '""')}"`);
const NOT_EXT = (col) => `not exists (select 1 from pg_depend d where d.objid = ${col} and d.deptype = 'e')`;
const ACL = (acl, kind, owner) => `coalesce((select json_agg(json_build_object('grantee', case when a.grantee = 0 then 'PUBLIC' else pg_get_userbyid(a.grantee) end, 'priv', a.privilege_type, 'go', a.is_grantable)) from aclexplode(coalesce(${acl}, acldefault('${kind}', ${owner}))) a), '[]'::json)`;

// "grant a, b on <what> to <role>;" lines, one per grantee, sorted.
const grantLines = (acl, what) => {
  const m = new Map();
  for (const a of acl || []) { const k = a.grantee + (a.go ? ' with grant option' : ''); if (!m.has(k)) m.set(k, new Set()); m.get(k).add(a.priv.toLowerCase()); }
  return [...m.keys()].sort().map((k) => { const [role, ...rest] = k.split(' '); return `grant ${[...m.get(k)].sort().join(', ')} on ${what} to ${role === 'PUBLIC' ? 'public' : qi(role)}${rest.length ? ' ' + rest.join(' ') : ''};`; });
};

const SECRET = [/eyJ[A-Za-z0-9_-]{20,}\.[A-Za-z0-9_-]{10,}/, /\bsbp_[A-Za-z0-9]{20,}/, /\bsk_(live|test)_[A-Za-z0-9]{10,}/, /[MN][A-Za-z\d]{23,}\.[\w-]{6}\.[\w-]{27,}/, /\bservice_role_key\b/i, /\bpassword\s*=\s*'[^']+'/i, /\bBearer\s+[A-Za-z0-9._-]{20,}/];
export const findSecrets = (files) => {
  const hits = [];
  for (const [path, text] of files) text.split('\n').forEach((l, i) => { if (SECRET.some((r) => r.test(l))) hits.push(`${path}:${i + 1}`); });
  return hits;
};

export async function readCatalog(q) {
  const Q = (sql) => q(assertSelect(sql));
  const rels = await Q(`
    select c.relname as name, c.relkind as kind, c.relrowsecurity as rls, c.relforcerowsecurity as rls_force, pg_get_userbyid(c.relowner) as owner,
           case when c.relkind in ('v', 'm') then pg_get_viewdef(c.oid, true) end as viewdef,
           ${ACL('c.relacl', 'r', 'c.relowner')} as acl
      from pg_class c join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'public' and c.relkind in ('r', 'p', 'v', 'm', 'f') and ${NOT_EXT('c.oid')}`);
  const cols = await Q(`
    select c.relname as tbl, a.attnum as num, a.attname as name, format_type(a.atttypid, a.atttypmod) as type, a.attnotnull as notnull,
           pg_get_expr(d.adbin, d.adrelid) as def, a.attgenerated as gen, a.attidentity as ident,
           case when a.attcollation <> 0 and a.attcollation <> t.typcollation then (select collname from pg_collation where oid = a.attcollation) end as coll,
           case when a.attacl is null then '[]'::json else ${ACL('a.attacl', 'c', 'c.relowner')} end as acl
      from pg_class c join pg_namespace n on n.oid = c.relnamespace
      join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
      join pg_type t on t.oid = a.atttypid
      left join pg_attrdef d on d.adrelid = c.oid and d.adnum = a.attnum
     where n.nspname = 'public' and c.relkind in ('r', 'p', 'v', 'm', 'f') and ${NOT_EXT('c.oid')}`);
  const cons = await Q(`
    select c.relname as tbl, k.conname as name, pg_get_constraintdef(k.oid) as def
      from pg_constraint k join pg_class c on c.oid = k.conrelid join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'public' and ${NOT_EXT('c.oid')}`);
  const idx = await Q(`
    select c.relname as tbl, i.relname as name, pg_get_indexdef(x.indexrelid) as def
      from pg_index x join pg_class c on c.oid = x.indrelid join pg_class i on i.oid = x.indexrelid join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'public' and ${NOT_EXT('c.oid')}`);
  const pols = await Q(`
    select c.relname as tbl, p.polname as name, p.polpermissive as permissive, p.polcmd as cmd,
           coalesce((select json_agg(case when r = 0 then 'public' else pg_get_userbyid(r) end) from unnest(p.polroles) r), '[]'::json) as roles,
           pg_get_expr(p.polqual, p.polrelid) as qual, pg_get_expr(p.polwithcheck, p.polrelid) as chk
      from pg_policy p join pg_class c on c.oid = p.polrelid join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'public'`);
  const trigs = await Q(`
    select c.relname as tbl, t.tgname as name, pg_get_triggerdef(t.oid) as def, t.tgenabled as enabled
      from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'public' and not t.tgisinternal`);
  const fns = await Q(`
    select p.proname as name, format('%I.%I(%s)', n.nspname, p.proname, oidvectortypes(p.proargtypes)) as ident, p.prokind as kind,
           pg_get_userbyid(p.proowner) as owner,
           case when p.prokind in ('f', 'p', 'w') then replace(pg_get_functiondef(p.oid), chr(13), '') end as def,
           case when p.prokind in ('f', 'p', 'w') then md5(replace(pg_get_functiondef(p.oid), chr(13), '')) end as md5,
           ${ACL('p.proacl', 'f', 'p.proowner')} as acl
      from pg_proc p join pg_namespace n on n.oid = p.pronamespace
     where n.nspname = 'public' and ${NOT_EXT('p.oid')}`);
  const enums = await Q(`
    select t.typname as name, json_agg(e.enumlabel order by e.enumsortorder) as labels
      from pg_type t join pg_namespace n on n.oid = t.typnamespace join pg_enum e on e.enumtypid = t.oid
     where n.nspname = 'public' and ${NOT_EXT('t.oid')} group by t.typname`);
  const domains = await Q(`
    select t.typname as name, format_type(t.typbasetype, t.typtypmod) as base, t.typnotnull as notnull, t.typdefault as def,
           coalesce((select json_agg(pg_get_constraintdef(k.oid) order by k.conname) from pg_constraint k where k.contypid = t.oid), '[]'::json) as checks
      from pg_type t join pg_namespace n on n.oid = t.typnamespace
     where n.nspname = 'public' and t.typtype = 'd' and ${NOT_EXT('t.oid')}`);
  const composites = await Q(`
    select t.typname as name, json_agg(a.attname || ' ' || format_type(a.atttypid, a.atttypmod) order by a.attnum) as attrs
      from pg_type t join pg_namespace n on n.oid = t.typnamespace join pg_class c on c.oid = t.typrelid and c.relkind = 'c'
      join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
     where n.nspname = 'public' and ${NOT_EXT('t.oid')} group by t.typname`);
  const seqs = await Q(`
    select c.relname as name, format_type(s.seqtypid, null) as type, s.seqstart as start, s.seqincrement as inc, s.seqmin as min, s.seqmax as max, s.seqcycle as cycle,
           (select tc.relname || '.' || a.attname from pg_depend d join pg_class tc on tc.oid = d.refobjid join pg_attribute a on a.attrelid = d.refobjid and a.attnum = d.refobjsubid
             where d.objid = c.oid and d.classid = 'pg_class'::regclass and d.deptype in ('a', 'i') limit 1) as owned_by,
           ${ACL('c.relacl', 's', 'c.relowner')} as acl
      from pg_sequence s join pg_class c on c.oid = s.seqrelid join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'public' and ${NOT_EXT('c.oid')}`);
  const exts = await Q(`select e.extname as name, e.extversion as version, n.nspname as schema from pg_extension e join pg_namespace n on n.oid = e.extnamespace`);
  const hasCron = (await Q(`select to_regclass('cron.job') is not null as yes`))[0]?.yes;
  const cron = hasCron ? await Q(`select jobname as name, schedule, command, active from cron.job`) : [];
  return { rels, cols, cons, idx, pols, trigs, fns, enums, domains, composites, seqs, exts, cron, hasCron };
}

const KIND = { r: 'table', p: 'partitioned table', v: 'view', m: 'materialized view', f: 'foreign table' };
const CMD = { r: 'select', a: 'insert', w: 'update', d: 'delete', '*': 'all' };

/** The snapshot files from a catalog (readCatalog). */
export function renderSnapshot(cat) {
  const files = new Map();
  const put = (path, lines) => files.set(path, lf(lines.join('\n')).replace(/\n+$/, '') + '\n');
  const group = (rows) => { const m = new Map(); for (const r of rows) { if (!m.has(r.tbl)) m.set(r.tbl, []); m.get(r.tbl).push(r); } return m; };
  const colsBy = group(cat.cols), consBy = group(cat.cons), idxBy = group(cat.idx), polsBy = group(cat.pols), trigsBy = group(cat.trigs);

  // ---- One file per table or view. ----
  for (const t of [...cat.rels].sort(by((r) => r.name))) {
    const name = `public.${qi(t.name)}`;
    const L = [HEADER, `-- ${KIND[t.kind] || t.kind} ${name}`, '', '-- @owner', `-- owner: ${t.owner}`, ''];
    const cs = (colsBy.get(t.name) || []).sort((a, b) => a.num - b.num);
    if (t.kind === 'v' || t.kind === 'm') {
      L.push('-- @definition', `create ${t.kind === 'm' ? 'materialized view' : 'view'} ${name} as`, lf(t.viewdef).replace(/\s+$/, '').replace(/;$/, '') + ';', '');
      L.push('-- @columns', ...cs.map((c) => `--   ${qi(c.name)} ${c.type}`), '');
    } else {
      const colLine = (c) => {
        let s = `  ${qi(c.name)} ${c.type}`;
        if (c.coll) s += ` collate "${c.coll}"`;
        if (c.gen === 's') s += ` generated always as (${lf(c.def)}) stored`;
        else if (c.def != null) s += ` default ${lf(c.def)}`;
        if (c.ident === 'a') s += ' generated always as identity'; else if (c.ident === 'd') s += ' generated by default as identity';
        if (c.notnull) s += ' not null';
        return s;
      };
      L.push('-- @columns', `create table ${name} (`, cs.map(colLine).join(',\n'), ');', '');
    }
    const ks = (consBy.get(t.name) || []).sort(by((k) => k.name));
    if (ks.length) L.push('-- @constraints', ...ks.map((k) => `alter table ${name} add constraint ${qi(k.name)} ${flattenAnd(lf(k.def))};`), '');
    const ix = (idxBy.get(t.name) || []).sort(by((k) => k.name));
    if (ix.length) L.push('-- @indexes', ...ix.map((k) => `${flattenAnd(lf(k.def))};`), '');
    if (t.kind === 'r' || t.kind === 'p') L.push('-- @rls', `alter table ${name} ${t.rls ? 'enable' : 'disable'} row level security;`, ...(t.rls_force ? [`alter table ${name} force row level security;`] : []), '');
    const ps = (polsBy.get(t.name) || []).sort(by((p) => p.name));
    if (ps.length) {
      L.push('-- @policies');
      for (const p of ps) {
        L.push(`create policy ${qi(p.name)} on ${name} as ${p.permissive ? 'permissive' : 'restrictive'} for ${CMD[p.cmd] || p.cmd} to ${[...p.roles].sort().join(', ')}` +
          `${p.qual != null ? `\n  using (${flattenAnd(lf(p.qual))})` : ''}${p.chk != null ? `\n  with check (${flattenAnd(lf(p.chk))})` : ''};`);
      }
      L.push('');
    }
    L.push('-- @grants', ...grantLines(t.acl, `table ${name}`));
    for (const c of cs) if ((c.acl || []).length) L.push(...grantLines(c.acl, `table ${name}`).map((g) => g.replace(/^grant ([^ ]+(?:, [^ ]+)*) on/, (m, privs) => `grant ${privs.split(', ').map((p) => `${p} (${qi(c.name)})`).join(', ')} on`)));
    L.push('');
    const tg = (trigsBy.get(t.name) || []).sort(by((k) => k.name));
    if (tg.length) L.push('-- @triggers', ...tg.map((k) => `${lf(k.def)};${k.enabled === 'O' ? '' : ` -- enabled: ${k.enabled}`}`), '');
    put(`tables/${t.name}.sql`, L);
  }

  // ---- One file per function name (an overload goes into the same file, sorted by its signature). ----
  const fnsBy = new Map();
  for (const f of cat.fns) { if (!fnsBy.has(f.name)) fnsBy.set(f.name, []); fnsBy.get(f.name).push(f); }
  for (const name of [...fnsBy.keys()].sort()) {
    const L = [HEADER];
    for (const f of fnsBy.get(name).sort(by((x) => x.ident))) {
      L.push('', `-- @function ${f.ident}`, `-- md5: ${f.md5 ?? '-'}   (${MD5_FORMULA(f.ident)})`, `-- owner: ${f.owner}`);
      L.push(f.def != null ? lf(f.def).replace(/\s+$/, '') + ';' : `-- ${f.kind === 'a' ? 'aggregate' : 'kind ' + f.kind}: no pg_get_functiondef`);
      L.push(`-- @grants ${f.ident}`, ...grantLines(f.acl, `function ${f.ident}`));
    }
    put(`functions/${name}.sql`, L);
  }
  // The md5 index: one line per function, the guard value of each.
  put('functions.md5', ['# ' + HEADER.slice(3), '# <md5>  <function>   md5 = ' + MD5_FORMULA('<function>'),
    ...[...cat.fns].sort(by((f) => f.ident)).map((f) => `${f.md5 ?? '-'}  ${f.ident}`)]);

  // ---- Types, sequences, extensions, cron jobs. ----
  const T = [HEADER, ''];
  T.push('-- @enums', ...[...cat.enums].sort(by((e) => e.name)).map((e) => `create type public.${qi(e.name)} as enum (${e.labels.map((l) => `'${l.replace(/'/g, "''")}'`).join(', ')});`), '');
  T.push('-- @domains', ...[...cat.domains].sort(by((d) => d.name)).map((d) => `create domain public.${qi(d.name)} as ${d.base}${d.def != null ? ` default ${lf(d.def)}` : ''}${d.notnull ? ' not null' : ''}${d.checks.map((c) => ` ${lf(c)}`).join('')};`), '');
  T.push('-- @composite types', ...[...cat.composites].sort(by((c) => c.name)).map((c) => `create type public.${qi(c.name)} as (${c.attrs.join(', ')});`));
  put('types.sql', T);
  const S = [HEADER, '-- The structure of each sequence. The current value is data: it is not here.', '', '-- @sequences'];
  for (const s of [...cat.seqs].sort(by((x) => x.name))) {
    S.push(`create sequence public.${qi(s.name)} as ${s.type} start ${s.start} increment ${s.inc} minvalue ${s.min} maxvalue ${s.max}${s.cycle ? ' cycle' : ''}${s.owned_by ? ` owned by public.${s.owned_by}` : ''};`,
      ...grantLines(s.acl, `sequence public.${qi(s.name)}`));
  }
  put('sequences.sql', S);
  put('extensions.sql', [HEADER, '', '-- @extensions', ...[...cat.exts].sort(by((e) => e.name)).map((e) => `create extension ${qi(e.name)} with schema ${qi(e.schema)} version '${e.version}';`)]);
  return files;
}

/** The cron jobs file (kept apart: the local copy has no cron jobs, see gen-schema-snapshot.mjs). */
export function renderCron(cat) {
  const L = [HEADER, '-- The pg_cron jobs (cron.job): name, schedule, active, command. Read from LIVE (the local copy has no jobs).', '', '-- @cron'];
  for (const j of [...cat.cron].sort(by((x) => x.name))) {
    L.push(`select cron.schedule('${j.name}', '${j.schedule}', $cron$${lf(j.command).trim()}$cron$);${j.active ? '' : ' -- active: false'}`);
  }
  return lf(L.join('\n')) + '\n';
}
