// ---- Compare two snapshots (Map path -> text). Returns [{ object, kind, detail }]. ----
const sections = (text) => {
  const m = new Map(); let cur = '(header)';
  for (const line of text.split('\n')) {
    const s = line.match(/^-- @(.+)$/);
    if (s) { cur = s[1].trim(); if (!m.has(cur)) m.set(cur, []); continue; }
    if (!m.has(cur)) m.set(cur, []);
    m.get(cur).push(line);
  }
  return m;
};
const objectOf = (path) => {
  if (path.startsWith('tables/')) return `table public.${path.slice(7, -4)}`;
  if (path.startsWith('functions/')) return `function public.${path.slice(10, -4)}`;
  return path;
};
export function compareSnapshots(expected, actual) {
  const diffs = [];
  // functions.md5 repeats the md5 lines of the function files: one difference is reported once.
  const paths = [...new Set([...expected.keys(), ...actual.keys()])].filter((p) => p !== 'functions.md5').sort();
  for (const p of paths) {
    const a = expected.get(p), b = actual.get(p);
    if (a === b) continue;
    if (a == null) { diffs.push({ object: objectOf(p), kind: 'not in the snapshot (new in the database)', file: p }); continue; }
    if (b == null) { diffs.push({ object: objectOf(p), kind: 'missing in the database (in the snapshot only)', file: p }); continue; }
    const sa = sections(a), sb = sections(b);
    for (const k of [...new Set([...sa.keys(), ...sb.keys()])].sort()) {
      const x = (sa.get(k) || []).join('\n').trim(), y = (sb.get(k) || []).join('\n').trim();
      if (x === y) continue;
      const xl = new Set(x.split('\n')), yl = new Set(y.split('\n'));
      const minus = [...xl].filter((l) => !yl.has(l)), plus = [...yl].filter((l) => !xl.has(l));
      let kind = k, object = objectOf(p);
      const fm = k.match(/^(function|grants) (.+)$/);
      if (fm) { object = `function ${fm[2]}`; kind = fm[1] === 'function' ? (x && y ? 'definition (md5) differs' : x ? 'missing in the database' : 'not in the snapshot') : 'grants'; }
      diffs.push({ object, kind, file: p, minus, plus });
    }
  }
  return diffs;
}

export const printDiffs = (diffs, { max = 6 } = {}) => {
  for (const d of diffs) {
    console.log(`  DIFF ${d.object}: ${d.kind}`);
    const show = (sign, list) => { for (const l of (list || []).slice(0, max)) console.log(`         ${sign} ${l.length > 160 ? l.slice(0, 160) + ' ...' : l}`); if ((list || []).length > max) console.log(`         ${sign} ... ${(list.length - max)} more line(s)`); };
    show('snapshot:', d.minus); show('database:', d.plus);
  }
};
